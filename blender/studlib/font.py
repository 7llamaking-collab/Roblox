"""Blocky 3x5 pixel font: real lettering for signs, number plates, badges...

``text(m, "BANK", x, y, z)`` builds the letters as small boxes standing in the XZ
plane just in front of ``y`` (towards -Y), centred on (x, z).
"""


def blk(m, size, loc, col):
    return m.box(size, color=col, bevel=0.0, loc=loc)


